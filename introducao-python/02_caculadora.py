
# Calculadora simples

# SOMA
print("1 + 1 = ", 1 + 1)

# SUBTRAÇÃO
print("1 - 1 = ", 1 - 1)

# MULTIPLICAÇÃO
print("1 * 1 = ", 1 * 1)

# DIVISÃO
print("1 / 1 = ", 1 / 1)

# DIVISÃO INTEIRA
print("10 // 3 = ", 10 // 3)

# RESTO DA DIVISÃO
print("1 % 1 = ", 1 % 1)

# POTENCIAÇÃO
print("1 ** 1 = ", 1 ** 1)

