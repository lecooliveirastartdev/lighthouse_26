# Tipos de dados
# int: números inteiros
# float: números reais
# str: strings
# bool: booleanos
# list: listas
# dict: dicionários
# tuple: tuplas
# set: conjuntos

#Variáveis: são espaços na memória do computador para armazenar valores
#Nome da variável: nome = valor
#Exemplo:
nome = "João"
idade = 20
altura = 1.75
peso = 70
imc = peso / (altura ** 2)
print(imc)
print(nome)
print(idade)
print(altura)
print(peso)
print(imc)

# type: é uma função que permite que o usuário digite um valor
# Exemplo:
print("--------------------------------")
print(type(nome))
print(type(idade)) # int
print(type(altura)) # float
print(type(peso)) # int
print(type(imc)) # float
